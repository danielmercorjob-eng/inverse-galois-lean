"""Variants of the inverse Galois problem for a permutation group, and their Lean statements.

Each `Variant` becomes one self-contained Formal Conjectures problem file with exactly one
`sorry`: the proof of its main theorem.
"""

import re
import textwrap
from dataclasses import dataclass
from typing import Optional

from .group import GroupSpec, cycles_to_str, from_cycles

KINDS = ("polynomial", "realizable", "regular")
ACTIONS = ("abstract", "roots")
NORMALIZATIONS = ("any", "monic", "monic_irreducible")
NAMESPACE_ROOT = "InverseGaloisVariants"
GENERATED_MARKER = "Generated by inverse-galois-lean"
QPOLY = "(f.map (Int.castRingHom ℚ))"


def camel_to_snake(s: str) -> str:
    s = re.sub(r"(?<=[a-z])(?=[A-Z0-9])|(?<=[0-9])(?=[A-Z])", "_", s)
    return s.lower()


@dataclass
class Variant:
    group: GroupSpec
    kind: str = "polynomial"
    action: str = "abstract"
    normalization: str = "any"
    digits: Optional[int] = None  # coefficients have fewer than `digits` decimal digits
    real_roots: Optional[int] = None

    def __post_init__(self):
        if self.kind not in KINDS:
            raise ValueError(f"unknown kind {self.kind!r}")
        if self.kind != "polynomial":
            return
        if self.action not in ACTIONS:
            raise ValueError(f"unknown action {self.action!r}")
        if self.normalization not in NORMALIZATIONS:
            raise ValueError(f"unknown normalization {self.normalization!r}")
        if self.normalization == "monic_irreducible" and not self.group.transitive:
            raise ValueError(f"{self.group.name} is intransitive, so no irreducible polynomial "
                             "has it as Galois group")
        if self.digits is not None and self.digits < 1:
            raise ValueError("digit bound must be at least 1")
        if self.real_roots is not None and self.real_roots not in self.group.real_root_counts():
            raise ValueError(
                f"{self.group.name}: a polynomial with this Galois group has "
                f"{self.group.real_root_counts()} real roots (complex conjugation acts as an "
                f"involution or trivially), not {self.real_roots}")

    # -- naming ---------------------------------------------------------------

    @property
    def stem(self) -> str:
        """The Lean module (file) name, in UpperCamelCase."""
        if self.kind == "realizable":
            return "Realizable"
        if self.kind == "regular":
            return "RegularOverRatFunc"
        parts = ["Poly", {"abstract": "GalIso", "roots": "RootAction"}[self.action],
                 {"any": "", "monic": "Monic", "monic_irreducible": "MonicIrreducible"}
                 [self.normalization],
                 "Unbounded" if self.digits is None else f"Digits{self.digits}"]
        if self.real_roots is not None:
            parts.append("TotallyReal" if self.real_roots == self.group.degree
                         else f"RealRoots{self.real_roots}")
        return "".join(parts)

    @property
    def theorem_name(self) -> str:
        return f"{self.group.snake}_{camel_to_snake(self.stem)}"

    @property
    def namespace(self) -> str:
        return f"{NAMESPACE_ROOT}.{self.group.name}{self.stem}"

    # -- status -----------------------------------------------------------------

    @property
    def status(self) -> str:
        """`solved`, `open`, or `unknown` (not settled by the facts in the group file).

        A polynomial variant is `solved` when a known polynomial in the group file satisfies all
        of its conditions, or when it has no digit bound and no real-root condition and the
        group is realizable: then scaling gives a monic polynomial, and a transitive Galois group
        makes it irreducible.
        """
        st = self.group.status
        realizable = st.get("realizable")
        if self.kind == "realizable":
            return realizable or "unknown"
        if self.kind == "regular":
            return st.get("regular") or "unknown"
        if realizable == "open":
            return "open"  # every polynomial variant implies realizability
        if any(k.satisfies(self) for k in self.group.known):
            return "solved"
        if self.digits is None and self.real_roots is None:
            return realizable or "unknown"
        return "unknown"

    @property
    def category(self) -> str:
        return "solved" if self.status == "solved" else "open"

    def status_note(self) -> str:
        notes = self.group.notes
        key = "regular" if self.kind == "regular" else "realizable"
        if self.status == "solved":
            witness = next((k for k in self.group.known if k.satisfies(self)), None) \
                if self.kind == "polynomial" else None
            if witness is not None and witness.source:
                base = f"Solved: the known polynomial {witness.source} satisfies these conditions."
            elif self.kind == "polynomial":
                base = (notes.get(key, "") + " Without a digit bound, scaling gives a monic "
                        "polynomial, and a transitive Galois group makes it irreducible.")
            else:
                base = notes.get(key, "")
            return (base.strip() + " There is no formal proof.").strip()
        if self.status == "open":
            return notes.get(key) or "This problem is open."
        return "This variant is marked open because we know of no source that settles it."

    # -- text -------------------------------------------------------------------

    def title(self) -> str:
        g = f"${self.group.latex}$"
        if self.kind == "realizable":
            return f"{g} is a Galois group over $\\mathbb{{Q}}$"
        if self.kind == "regular":
            return f"{g} is a regular Galois group over $\\mathbb{{Q}}(t)$"
        adj = {"any": "", "monic": "monic ", "monic_irreducible": "monic irreducible "}
        title = f"a degree-{self.group.degree} {adj[self.normalization]}polynomial with Galois group {g}"
        extra = []
        if self.digits is not None:
            extra.append(f"coefficients of fewer than {self.digits} digits")
        if self.real_roots == self.group.degree:
            extra.append("all roots real")
        elif self.real_roots is not None:
            extra.append(f"exactly {self.real_roots} real roots")
        if self.action == "roots":
            extra.append("as a permutation group of the roots")
        return title + (" (" + "; ".join(extra) + ")" if extra else "")

    def docstring(self) -> str:
        g, n = f"${self.group.latex}$", self.group.degree
        if self.kind == "realizable":
            return (f"There is a finite Galois extension $L / \\mathbb{{Q}}$ whose Galois group "
                    f"is isomorphic to {g}.")
        if self.kind == "regular":
            return (f"There is a finite Galois extension $L / \\mathbb{{Q}}(t)$ with Galois group "
                    f"isomorphic to {g} in which $\\mathbb{{Q}}$ is algebraically closed.")
        adj = "" if self.normalization == "any" else "monic "
        s = f"There is a {adj}polynomial $f \\in \\mathbb{{Z}}[x]$ of degree ${n}$"
        conds = []
        if self.normalization == "monic_irreducible":
            conds.append("irreducible over $\\mathbb{Q}$")
        if self.digits is not None:
            conds.append(f"whose coefficients each have fewer than ${self.digits}$ decimal digits")
        if self.real_roots == n:
            conds.append(f"with all ${n}$ roots real")
        elif self.real_roots is not None:
            conds.append(f"with exactly ${self.real_roots}$ real roots")
        if conds:
            s += ", " + ", ".join(conds) + ","
        if self.action == "abstract":
            s += f" whose Galois group over $\\mathbb{{Q}}$ is isomorphic to {g}."
        else:
            s += (f" whose Galois group acts on the ${n}$ complex roots exactly as {g} acts on"
                  f" $\\{{0, \\dots, {n - 1}\\}}$, for some labelling of the roots.")
        return s

    def statement(self) -> str:
        """The Lean statement, indented for use after `theorem name :`."""
        G, n = self.group.name, self.group.degree
        if self.kind == "realizable":
            return ("∃ (L : Type) (_ : Field L) (_ : Algebra ℚ L),\n"
                    f"      FiniteDimensional ℚ L ∧ IsGalois ℚ L ∧ Nonempty ((L ≃ₐ[ℚ] L) ≃* {G})")
        if self.kind == "regular":
            emb = "((algebraMap (RatFunc ℚ) L).comp (algebraMap ℚ (RatFunc ℚ)))"
            return ("∃ (L : Type) (_ : Field L) (_ : Algebra (RatFunc ℚ) L),\n"
                    "      FiniteDimensional (RatFunc ℚ) L ∧ IsGalois (RatFunc ℚ) L ∧\n"
                    f"      Nonempty ((L ≃ₐ[RatFunc ℚ] L) ≃* {G}) ∧\n"
                    f"      ∀ x : L, {emb}.IsIntegralElem x →\n"
                    f"        x ∈ {emb}.range")
        conds = [f"f.natDegree = {n}"]
        if self.normalization != "any":
            conds.append("f.Monic")
        if self.normalization == "monic_irreducible":
            conds.append(f"Irreducible {QPOLY}")
        if self.digits is not None:
            conds.append(f"(∀ i, (Nat.digits 10 (f.coeff i).natAbs).length < {self.digits})")
        if self.real_roots is not None:
            conds.append(f"({QPOLY}.rootSet ℝ).ncard = {self.real_roots}")
        if self.action == "abstract":
            conds.append(f"Nonempty ({QPOLY}.Gal ≃* {G})")
        else:
            conds.append(f"∃ e : {QPOLY}.rootSet ℂ ≃ Fin {n},\n"
                         f"        Set.range (fun g ↦ e.permCongr (Gal.galActionHom {QPOLY} ℂ g)) =\n"
                         f"          ({G} : Set (Equiv.Perm (Fin {n})))")
        return "∃ f : ℤ[X], " + " ∧\n      ".join(conds)

    def needs_complex_splits(self) -> bool:
        return self.kind == "polynomial" and self.action == "roots"


