SUBSCRIPTS = str.maketrans("0123456789", "₀₁₂₃₄₅₆₇₈₉")


def _wrap(text: str, first: str = "", width: int = 100) -> str:
    return textwrap.fill(text, width=width, initial_indent=first, subsequent_indent="",
                         break_long_words=False, break_on_hyphens=False)


def _check_lines(text: str, stem: str, width: int = 100):
    for n, line in enumerate(text.splitlines(), 1):
        if len(line) > width and "http" not in line:
            raise ValueError(f"{stem}.lean:{n} is longer than {width} characters")


def _short_cycles(cycles, n):
    if len(cycles) == 1 and list(cycles[0]) == list(range(1, n + 1)):
        return f"(1 2 … {n})"
    return cycles_to_str(cycles)


def _lean_perm(cycles, n):
    """A Lean term of type `Equiv.Perm (Fin n)` for the 1-indexed `cycles`."""
    if len(cycles) == 1 and list(cycles[0]) == list(range(1, n + 1)):
        return f"(List.finRange {n}).formPerm"
    return " *\n    ".join("[" + ", ".join(str(x - 1) for x in c) + "].formPerm" for c in cycles)


def _spot_checks(name, cycles, n):
    """`decide`-able equations: one step of each cycle and up to two fixed points."""
    p = from_cycles(cycles, n)
    points = [c[0] - 1 for c in cycles] + [i for i in range(n) if p[i] == i][:2]
    return " ∧\n    ".join(f"{name} {i} = {p[i]}" for i in points)


def _reference_lines(group):
    out = []
    for r in group.references:
        if r.get("url"):
            out.append(f"*Reference:* [{r['title']}]({r['url']})")
        else:
            out.append(_wrap(f"*Reference:* {r['title']}"))
    return "\n".join(out)


def render(v: Variant) -> str:
    """The full contents of the Lean file for `v`."""
    g, n = v.group, v.group.degree
    gen_names = [f"gen{str(i + 1).translate(SUBSCRIPTS)}" for i in range(len(g.generators))]
    gens_short = [_short_cycles(c, n) for c in g.generators]
    defs = []
    for name, cycles, short in zip(gen_names, g.generators, gens_short):
        defs.append(_wrap(f"The permutation `{short}`, with every point shifted down by one. -/",
                          first="/-- ") + "\n"
                    f"def {name} : Equiv.Perm (Fin {n}) :=\n    {_lean_perm(cycles, n)}\n")
        defs.append(f"@[category test, AMS 20]\n"
                    f"theorem {name}_spec :\n    {_spot_checks(name, cycles, n)} := by\n"
                    f"  decide\n")
    transitive = "transitive " if g.transitive else ""
    definition_note = (
        f"Here ${g.latex}$ is {g.description}, as the subgroup of `Equiv.Perm (Fin {n})` "
        f"generated by " + " and ".join(f"`{s}`" for s in gens_short) +
        f" (written 1-indexed). This {transitive}group has order ${g.order}$. "
        + g.identification).strip()
    local_instance = ("\nattribute [local instance] Polynomial.Gal.splits_ℚ_ℂ\n"
                      if v.needs_complex_splits() else "")
    text = f"""{HEADER}
/-!
# Inverse Galois problem for ${g.latex}$

{_wrap("Variant: " + v.title() + ".")}

{_wrap(v.docstring())}

{_wrap(v.status_note())}

{_wrap(definition_note)}

{_reference_lines(g)}

{GENERATED_MARKER}.
-/

@[expose] public section

namespace {v.namespace}

open Polynomial
{local_instance}
{chr(10).join(defs)}
{_wrap(g.description[0].upper() + g.description[1:] + ". -/", first="/-- ")}
def {g.name} : Subgroup (Equiv.Perm (Fin {n})) := Subgroup.closure {{{", ".join(gen_names)}}}

{_wrap(v.docstring() + " -/", first="/-- ")}
@[category research {v.category}, AMS 12]
theorem {v.theorem_name} :
    {v.statement()} := by
  sorry

end {v.namespace}
"""
    _check_lines(text, f"{g.name}/{v.stem}")
    return text
