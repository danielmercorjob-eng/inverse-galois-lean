@dataclass
class GroupSpec:
    name: str  # Lean identifier, folder name and namespace component
    latex: str  # e.g. `M_{23}`, used in docstrings as `$M_{23}$`
    description: str
    degree: int
    order: int
    generators: list  # list of permutations, each a list of 1-indexed cycles
    identification: str = ""
    status: dict = field(default_factory=dict)
    notes: dict = field(default_factory=dict)
    references: list = field(default_factory=list)
    known_polynomials: list = field(default_factory=list)

    def __post_init__(self):
        if not re.fullmatch(r"[A-Z][A-Za-z0-9]*", self.name):
            raise ValueError(f"group name {self.name!r} must be an UpperCamelCase identifier")
        if self.degree < 2:
            raise ValueError("degree must be at least 2")
        for key in ("realizable", "regular"):
            if self.status.get(key) not in (None, *STATUSES):
                raise ValueError(f"{self.name}: status.{key} must be one of {STATUSES} or absent")
        self.known = [KnownPolynomial.from_json(k) for k in self.known_polynomials]
        for k in self.known:
            if k.degree is not None and k.degree != self.degree:
                raise ValueError(f"{self.name}: known polynomial of degree {k.degree}, "
                                 f"expected {self.degree}")
        for gen in self.generators:
            for c in gen:
                if not all(1 <= x <= self.degree for x in c) or len(set(c)) != len(c):
                    raise ValueError(f"{self.name}: bad cycle {c}")

    @classmethod
    def load(cls, path):
        return cls(**json.loads(Path(path).read_text()))

    @property
    def perms(self):
        return [from_cycles(g, self.degree) for g in self.generators]

    @property
    def transitive(self):
        return is_transitive(self.perms)

    @property
    def snake(self):
        """`M23` ↦ `m23`, `PSL27` ↦ `psl27`."""
        return re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", self.name).lower()

    def verify(self):
        """Raise `AssertionError` unless the generators generate a group of the declared order."""
        order = group_order(self.perms)
        assert order == self.order, (
            f"{self.name}: generators generate a group of order {order}, not {self.order}")
        return order

    def real_root_counts(self):
        """Possible numbers of real roots of a polynomial with this Galois action."""
        return sorted({self.degree} | involution_fixed_point_counts(self.perms), reverse=True)


def load_groups(names=None, directory=GROUPS_DIR):
    groups = {g.name: g for g in map(GroupSpec.load, sorted(Path(directory).glob("*.json")))}
    if names is None:
        return list(groups.values())
    missing = [n for n in names if n not in groups]
    if missing:
        raise ValueError(f"unknown groups {missing}; available: {sorted(groups)}")
    return [groups[n] for n in names]


def _self_test():
    assert group_order([from_cycles([(1, 2, 3)], 5), from_cycles([(1, 2, 3, 4, 5)], 5)]) == 60
    assert group_order([from_cycles([tuple(range(1, 9))], 8), from_cycles([(1, 2)], 8)]) \
        == factorial(8)


if __name__ == "__main__":
    _self_test()
    for g in load_groups():
        print(f"{g.name}: order {g.verify()}, transitive {g.transitive}, "
              f"real root counts {g.real_root_counts()}")
