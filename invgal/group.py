"""Finite permutation groups described by JSON files in `groups/`.

A group file gives generators in 1-indexed cycle notation, the degree, the order, and what
is known about the inverse Galois problem for the group. See `groups/M23.json`.

`GroupSpec.verify` checks the declared order with a small dependency-free
Schreier-Sims implementation. Run `python3 -m invgal.group` to check every group file.
"""

import json
import random
import re
from dataclasses import dataclass, field
from math import factorial
from pathlib import Path
from typing import Optional

from .poly import KnownPolynomial

GROUPS_DIR = Path(__file__).resolve().parent.parent / "groups"
STATUSES = ("solved", "open")

# ---------------------------------------------------------------------------
# Permutations as tuples `p` with `p[i]` the image of `i` (0-indexed).


def identity(n):
    return tuple(range(n))


def mul(p, q):
    """Apply p first, then q."""
    return tuple(q[p[i]] for i in range(len(p)))


def inv(p):
    r = [0] * len(p)
    for i, x in enumerate(p):
        r[x] = i
    return tuple(r)


def from_cycles(cycles, n):
    """Build a permutation of `n` points from 1-indexed cycles."""
    p = list(range(n))
    for c in cycles:
        for i, x in enumerate(c):
            p[x - 1] = c[(i + 1) % len(c)] - 1
    return tuple(p)


def cycles_to_str(cycles):
    """1-indexed cycle notation, e.g. `(3 17 10 7 9)(4 13 14 19 5)`."""
    return "".join("(" + " ".join(map(str, c)) + ")" for c in cycles)


def group_order(gens):
    """Order of the permutation group generated by `gens` (deterministic Schreier-Sims)."""
    n = len(gens[0])
    ident = identity(n)
    base, strong, orbits = [], [], []

    def orbit(b, gs):
        t = {b: ident}
        queue = [b]
        for x in queue:
            for g in gs:
                y = g[x]
                if y not in t:
                    t[y] = mul(t[x], g)
                    queue.append(y)
        return t

    def sift(g, start):
        for i in range(start, len(base)):
            y = g[base[i]]
            if y not in orbits[i]:
                return g, i
            g = mul(g, inv(orbits[i][y]))
        return g, len(base)

    def add(g, level):
        if level == len(base):
            b = next(x for x in range(n) if g[x] != x)
            base.append(b)
            strong.append([])
            orbits.append({b: ident})
        strong[level].append(g)
        close(level)

    def gens_at(i):
        return [g for j in range(i, len(strong)) for g in strong[j]]

    def close(top):
        # Re-establish the stabiliser chain at levels `top, ..., 0` by sifting every
        # Schreier generator.
        for lvl in range(top, -1, -1):
            gs = gens_at(lvl)
            orbits[lvl] = orbit(base[lvl], gs)
            for x, u in list(orbits[lvl].items()):
                for s in gs:
                    h = mul(mul(u, s), inv(orbits[lvl][s[x]]))
                    r, j = sift(h, lvl + 1)
                    if r != ident:
                        add(r, j)
                        return close(top)

    for g in gens:
        r, j = sift(g, 0)
        if r != ident:
            add(r, j)
    order = 1
    for o in orbits:
        order *= len(o)
    return order


def is_transitive(gens):
    n = len(gens[0])
    seen, queue = {0}, [0]
    for x in queue:
        for g in gens:
            if g[x] not in seen:
                seen.add(g[x])
                queue.append(g[x])
    return len(seen) == n


def involution_fixed_point_counts(gens, samples=2000, word_length=40, seed=0):
    """Fixed-point counts of involutions found in random elements of the group.

    Complex conjugation acts on the roots of a real polynomial as an element of order at most
    2, so the number of real roots of a polynomial whose Galois group is this permutation group
    is the degree or one of these counts. The search is random, so a rare class of involutions
    can be missed.
    """
    n = len(gens[0])
    ident = identity(n)
    rng = random.Random(seed)
    counts = set()
    for _ in range(samples):
        g = ident
        for _ in range(word_length):
            g = mul(g, rng.choice(gens))
        order, h = 1, g
        while h != ident:
            h, order = mul(h, g), order + 1
        if order % 2 == 0:
            t = ident
            for _ in range(order // 2):
                t = mul(t, g)
            counts.add(sum(t[i] == i for i in range(n)))
    return counts


