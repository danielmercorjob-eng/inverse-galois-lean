"""The Mathieu group M23 as a permutation group on 23 points.

This module holds the single source of truth for the generators of M23 used in the
generated Lean files. It can also check, with a small dependency-free
Schreier-Sims implementation, that the generators really generate M23:
the group is transitive of order 10200960, and M23 is the only transitive group of
degree 23 with that order.

Run `python3 -m igm23.group` to perform the check.
"""

from math import factorial

DEGREE = 23
M23_ORDER = 10200960  # 2^7 * 3^2 * 5 * 7 * 11 * 23

# 1-indexed cycle notation, as usually printed in the literature.
GEN1_CYCLES = [tuple(range(1, 24))]  # (1 2 3 ... 23)
GEN2_CYCLES = [(3, 17, 10, 7, 9), (4, 13, 14, 19, 5), (8, 18, 11, 12, 23), (15, 20, 22, 21, 16)]


def cycles_to_str(cycles):
    """Print cycles in 1-indexed notation, e.g. `(3 17 10 7 9)(4 13 14 19 5)`."""
    return "".join("(" + " ".join(map(str, c)) + ")" for c in cycles)


def zero_indexed(cycles):
    return [tuple(x - 1 for x in c) for c in cycles]


# ---------------------------------------------------------------------------
# Permutations as tuples `p` with `p[i]` the image of `i` (0-indexed).

ID = tuple(range(DEGREE))


def mul(p, q):
    """Apply p first, then q."""
    return tuple(q[p[i]] for i in range(len(p)))


def inv(p):
    r = [0] * len(p)
    for i, x in enumerate(p):
        r[x] = i
    return tuple(r)


def from_cycles(cycles, n=DEGREE):
    """Build a permutation from 1-indexed cycles."""
    p = list(range(n))
    for c in cycles:
        for i, x in enumerate(c):
            p[x - 1] = c[(i + 1) % len(c)] - 1
    return tuple(p)


def group_order(gens):
    """Order of the permutation group generated by `gens` (deterministic Schreier-Sims)."""
    n = len(gens[0])
    ident = tuple(range(n))
    base, strong, orbits = [], [], []

    def orbit(b, gs):
        t = {b: ident}
        queue = [b]
        for x in queue:
            for g in gs:
                y = g[x]
                if y not in t:
                    t[y] = mul(t[x], g)
                    queue.append(y)
        return t

    def sift(g, start):
        for i in range(start, len(base)):
            y = g[base[i]]
            if y not in orbits[i]:
                return g, i
            g = mul(g, inv(orbits[i][y]))
        return g, len(base)

    def add(g, level):
        if level == len(base):
            b = next(x for x in range(n) if g[x] != x)
            base.append(b)
            strong.append([])
            orbits.append({b: ident})
        strong[level].append(g)
        close(level)

    def gens_at(i):
        return [g for j in range(i, len(strong)) for g in strong[j]]

    def close(top):
        # Re-establish the stabiliser chain at levels `top, ..., 0` by sifting every
        # Schreier generator.
        for lvl in range(top, -1, -1):
            gs = gens_at(lvl)
            orbits[lvl] = orbit(base[lvl], gs)
            for x, u in list(orbits[lvl].items()):
                for s in gs:
                    h = mul(mul(u, s), inv(orbits[lvl][s[x]]))
                    r, j = sift(h, lvl + 1)
                    if r != ident:
                        add(r, j)
                        return close(top)

    for g in gens:
        r, j = sift(g, 0)
        if r != ident:
            add(r, j)
    order = 1
    for o in orbits:
        order *= len(o)
    return order


def is_transitive(gens):
    n = len(gens[0])
    seen, queue = {0}, [0]
    for x in queue:
        for g in gens:
            if g[x] not in seen:
                seen.add(g[x])
                queue.append(g[x])
    return len(seen) == n


def verify_m23():
    """Raise `AssertionError` unless the generators generate M23. Return the order."""
    # Sanity checks of the implementation itself.
    assert group_order([from_cycles([(1, 2, 3)], 5), from_cycles([(1, 2, 3, 4, 5)], 5)]) == 60
    gen1, gen2 = from_cycles(GEN1_CYCLES), from_cycles(GEN2_CYCLES)
    assert group_order([gen1, from_cycles([(1, 2)])]) == factorial(DEGREE)
    order = group_order([gen1, gen2])
    assert is_transitive([gen1, gen2]), "generators are not transitive"
    assert order == M23_ORDER, f"generated group has order {order}, expected {M23_ORDER}"
    return order


if __name__ == "__main__":
    print(f"order = {verify_m23()}: the generators generate M23")
